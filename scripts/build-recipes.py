def build():
    out = []
    for i, (title, goal, meal, minutes, yield_g, portions, ings, steps, tip) in enumerate(R, 1):
        total = {'kcal': 0.0, 'protein': 0.0, 'fat': 0.0, 'carbs': 0.0}
        items = []
        raw = 0
        for name, grams in ings:
            f = foods.get(name)
            if f is None:
                raise SystemExit(f'Нет продукта в базе: {name} (рецепт «{title}»)')
            k = grams / 100
            total['kcal'] += f['k'] * k
            total['protein'] += f['p'] * k
            total['fat'] += f['f'] * k
            total['carbs'] += f['u'] * k
            items.append({'n': name, 'g': grams})
            raw += grams

        scale = 100 / yield_g
        out.append({
            'id': f'r{i:03d}',
            'title': title,
            'goal': goal,
            'meal': meal,
            'minutes': minutes,
            'yieldGrams': yield_g,
            'rawGrams': raw,
            'portions': portions,
            'per100': {
                'kcal': round(total['kcal'] * scale),
                'protein': round(total['protein'] * scale, 1),
                'fat': round(total['fat'] * scale, 1),
                'carbs': round(total['carbs'] * scale, 1),
            },
            'items': items,
            'steps': steps,
            'tip': tip,
        })
        photo = PHOTOS.get(title)
        if photo:
            author = (photo.get('author') or '').strip()
            license_ = (photo.get('license') or '').strip()
            # Длинное имя автора не помещается в подпись на обложке.
            # У собственных снимков подписи нет вовсе.
            credit = f"{author[:34].rstrip(' ,')} · {license_}" if author else ''
            out[-1]['photo'] = {
                'src': photo['src'],
                'credit': credit,
                'source': photo.get('source', ''),
            }
    return out

recipes = build()
