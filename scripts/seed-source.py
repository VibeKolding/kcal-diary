def sid(name):
    """
    Идентификатор считается из названия, а не из порядка в списке.

    При нумерации по порядку удаление одного продукта сдвигало бы
    идентификаторы всех последующих, и ссылки на еду в «недавнем»
    и в сохранённых рецептах начали бы указывать на чужие продукты.
    """
    import hashlib
    return 'b' + hashlib.sha1(name.encode('utf-8')).hexdigest()[:10]

