import type { Nutrients } from '@/domain/types'

/** Жир — самое калорийное, что бывает: 9 ккал на грамм, 900 на 100 г */
export const MAX_KCAL_PER_100 = 900
/** Ни одного нутриента не может быть больше, чем весит сам продукт */
export const MAX_GRAMS_PER_100 = 100

/**
 * Что не так с составом на 100 г, или null, если всё правдоподобно.
 *
 * Свой продукт живёт в базе и множится на каждую запись: опечатка 2500
 * вместо 250 ккал завышала бы в десять раз каждый день, куда его добавят.
 * Поэтому невозможное не сохраняется, а объясняется. Расхождение калорий
 * с составом не проверяется: на этикетках оно бывает и честным — клетчатка,
 * спирт, округления.
 */
export function per100Problem(n: Nutrients): string | null {
  if (n.kcal > MAX_KCAL_PER_100) {
    return `В 100 г не бывает больше ${MAX_KCAL_PER_100} ккал — столько даёт чистый жир. Проверьте число.`
  }
  if (n.protein > MAX_GRAMS_PER_100 || n.fat > MAX_GRAMS_PER_100 || n.carbs > MAX_GRAMS_PER_100) {
    return `В 100 г продукта не может быть больше ${MAX_GRAMS_PER_100} г белков, жиров или углеводов.`
  }
  // Сумма — с округлением до десятых: 33.3 + 33.3 + 33.4 в плавающей
  // точке чуть больше ста, а на этикетке это ровно сто
  if (Math.round((n.protein + n.fat + n.carbs) * 10) / 10 > MAX_GRAMS_PER_100) {
    return `Белки, жиры и углеводы вместе не могут весить больше ${MAX_GRAMS_PER_100} г на 100 г продукта.`
  }
  return null
}
