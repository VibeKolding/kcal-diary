import type { Meal } from '@/domain/types'

/**
 * Приём пищи по времени суток — для «+» в таб-баре и ярлыка «Добавить еду»,
 * где приём никто не выбирал.
 *
 * Раньше такое открытие брало приём, выбранный в панели в прошлый раз:
 * утром записали завтрак — днём перекус тоже уходил в завтрак, и заметить
 * это было негде, а перенести запись в другой приём нельзя. Границы те же,
 * что у каталога блюд (11 и 16 часов), а поздний вечер и ночь — перекус:
 * ужин в полночь бывает реже, чем кефир перед сном.
 */
export function mealForTime(now: Date = new Date()): Meal {
  const h = now.getHours()
  if (h < 4) return 'snack'
  if (h < 11) return 'breakfast'
  if (h < 16) return 'lunch'
  if (h < 22) return 'dinner'
  return 'snack'
}
