/**
 * Таймер отдыха считает по часам, а не тиками.
 *
 * Раньше каждый тик setInterval отнимал секунду. Но пока телефон
 * заблокирован или вкладка заморожена, тиков нет вовсе, и после
 * разблокировки отсчёт продолжался с того места, где заснул: отдых
 * растягивался ровно на время блокировки. Момент окончания не зависит
 * от того, сколько раз успел сработать интервал.
 */
export function restLeft(endsAt: number, now: number = Date.now()): number {
  return Math.max(0, Math.ceil((endsAt - now) / 1000))
}

/** Сколько можно опоздать с вибрацией «отдых окончен», мс */
const BUZZ_LATE_MS = 3000

/**
 * Вибрировать ли в конце отдыха. Если отдых кончился, пока экран был
 * заблокирован, вибрация в момент разблокировки ничего не сообщает: человек
 * и так смотрит на телефон, а дрожь в руке путает.
 */
export function shouldBuzz(endsAt: number, now: number = Date.now()): boolean {
  return now - endsAt < BUZZ_LATE_MS
}
