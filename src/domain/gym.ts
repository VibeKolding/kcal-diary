import type { Sex } from './types'

/** Шесть групп мышц — верхний уровень раздела «Зал» */
export type MuscleGroup =
  | 'chest' | 'biceps' | 'triceps' | 'back' | 'shoulders' | 'legs'

/**
 * Кому упражнение адресовано.
 *
 * Мышцы у мужчин и женщин одни и те же, и выдумывать «женский жим» было бы
 * враньём. Разделение честное и узкое: часть движений попадает только в один
 * список, потому что под типичные запросы они нужны разной группе, а
 * подходы с повторами у общих движений отличаются — это поле `sets`.
 */
export type Audience = 'both' | Sex

/**
 * Куда идёт движение от левого кадра снимка-диптиха к правому.
 *
 * Значений четыре, а не три: у «поперёк» нет знака. В тяге каната руки идут
 * к лицу, в жиме ногами платформа уходит от тела — это движения в разные
 * стороны, и одна общая стрелка показала бы одно из них наоборот.
 */
export type Motion = 'up' | 'down' | 'left' | 'right'

export interface Exercise {
  id: string
  group: MuscleGroup
  title: string
  audience: Audience
  /** Что нужно из инвентаря. «Своё тело» означает, что не нужно ничего. */
  equipment: string
  /** На какой участок группы приходится нагрузка */
  focus: string
  /**
   * Подходы и повторы отдельно для каждого пола.
   *
   * Разница не в физиологии мышцы, а в типичной цели: под набор объёма
   * работают в более низком диапазоне повторов и с большим отдыхом, под
   * тонус и выносливость — в более высоком.
   */
  sets: Record<Sex, string>
  rest: string
  /**
   * Направление движения на снимке-диптихе: стрелку рисует приложение,
   * а не генератор картинок.
   *
   * Одно значение на упражнение, а не на снимок: снимков 69, по одному на
   * пару «упражнение × пол», но мужчина и женщина делают одно движение в
   * одну сторону. Кардинальность и показывает, чей это факт — упражнения,
   * а не кадра. Поэтому поле здесь, а не таблицей рядом с путём к файлу:
   * путь из `id` выводится, направление — нет.
   */
  motion: Motion
  steps: string[]
  mistakes: string[]
}

