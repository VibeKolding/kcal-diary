/**
 * Короткий тактильный отклик на завершённое действие: запись в дневник,
 * вес, стакан воды. Только там, где что-то сохранилось, — на обычные
 * нажатия телефон вибрировать не должен, это утомляет.
 *
 * iOS Safari API не поддерживает, и это нормально: отклик — приправа,
 * а не часть логики. Поэтому вызов молча ничего не делает там, где нельзя.
 */
export function tap(pattern: number | number[] = 8): void {
  try {
    navigator.vibrate?.(pattern)
  } catch {
    // некоторые браузеры бросают исключение вне пользовательского жеста
  }
}
